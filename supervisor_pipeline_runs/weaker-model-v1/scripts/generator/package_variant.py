"""
Writes the standard variant package (variant_manifest.json, variant.patch,
test.patch, validation.json) for a validated CONTROL or TREATMENT variant,
following the exact schema established throughout this project
(HANDOFF.md Section 6.3).
"""
import json
import os
import subprocess


def git_diff(checkout_dir, filepath_rel):
    result = subprocess.run(
        ["git", "diff", "--", filepath_rel], cwd=checkout_dir,
        capture_output=True, text=True,
    )
    return result.stdout


def git_diff_multi(checkout_dir, filepaths_rel):
    """Same as git_diff but for several files at once, combined into one
    patch (native `git diff -- f1 f2 f3` - preserves per-file diff headers,
    so the result applies cleanly with a single `git apply`)."""
    result = subprocess.run(
        ["git", "diff", "--"] + list(filepaths_rel), cwd=checkout_dir,
        capture_output=True, text=True,
    )
    return result.stdout


def package_variant(out_dir, variant_id, project, bug_id, source_file_rel, test_file_rel,
                     checkout_dir, gold_class, gold_method, trigger_test_id,
                     failing_tests, kind, design, seed_note):
    os.makedirs(out_dir, exist_ok=True)

    variant_patch = git_diff(checkout_dir, source_file_rel)
    test_patch = git_diff(checkout_dir, test_file_rel)

    manifest = {
        "schema_version": "d4j-variant-manifest/v1",
        "variant_id": variant_id,
        "status": "generation_incomplete",
        "benchmark_eligible": False,
        "source": {
            "defects4j_project": project,
            "defects4j_bug_id": bug_id,
            "bug_slug": f"{project}-{bug_id}",
            "baseline_version": f"fixed revision ({project}-{bug_id}f), unmodified except for "
                                 "this hand-designed variant",
            "artifact_path": f"new_bug_variants/{project}/bug-{bug_id}/L20/{variant_id}/",
        },
        "reproducibility": {
            "status": "not_checked",
            "note": [
                f"Generated by variant_generator (automated, LLM-designed, empirically validated "
                f"via real defects4j compile+test). {seed_note} "
                f"Kind: {kind}. Bug rationale: {design.bug_rationale}"
            ],
        },
        "difficulty_axis": {
            "kind": "distance_plus_lie_interaction_generated",
            "generator": "variant_generator (this project's automated pipeline, HANDOFF.md-derived recipe)",
            "predicted_correct_value": design.predicted_correct_value,
            "predicted_buggy_value": design.predicted_buggy_value,
        },
        "reasoning": {
            "level": "L20",
            "changed_node": f"{gold_class}#{gold_method}",
        },
        "fault": {
            "locations": [{
                "class": gold_class,
                "method": gold_method,
                "file": source_file_rel,
                "production": True,
            }],
            "gold": {"faulty_class": gold_class, "faulty_method": gold_method},
            "semantic_root_cause": design.bug_rationale,
        },
        "trigger": {
            "test_id": trigger_test_id,
            "all_empirically_failing_tests": failing_tests,
        },
        "artifacts": {
            "manifest": "variant_manifest.json",
            "variant_patch": "variant.patch",
            "test_patch": "test.patch",
            "validation": "validation.json",
        },
    }

    validation = {
        "schema_version": "d4j-validation/v1",
        "variant_id": variant_id,
        "status": "accepted",
        "accepted": True,
        "gate": {
            "variant_compile": {"status": "pass"},
            "variant_trigger": {"status": "expected_fail", "test_id": trigger_test_id},
            "production_fault": {"status": "pass", "known": True},
            "gold_method_known": {"status": "pass", "known": True},
        },
        "validated_with": {"baseline_revision": f"{project}-{bug_id}f"},
    }

    with open(os.path.join(out_dir, "variant_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    with open(os.path.join(out_dir, "variant.patch"), "w") as f:
        f.write(variant_patch)
    with open(os.path.join(out_dir, "test.patch"), "w") as f:
        f.write(test_patch)
    with open(os.path.join(out_dir, "validation.json"), "w") as f:
        json.dump(validation, f, indent=2)

    return out_dir


def package_variant_chain(out_dir, variant_id, project, bug_id, source_file_rel, test_file_rel,
                           host1_file_rel, host2_file_rel, checkout_dir, gold_class, gold_method,
                           trigger_test_id, failing_tests, kind, design, seed_note,
                           host1_class, host2_class, anchor1_name, anchor2_name, facade_method):
    """
    Same package as package_variant, for the two-file-crossing chain recipe
    (HANDOFF.md Sections 11.22/11.23 - the generalization-confirmed
    recipe): variant.patch covers THREE changed files (facade + host1 +
    host2) in one combined diff, and the manifest records the chain
    structure (which classes were crossed, hop names, where each hop was
    anchored) for audit/reproducibility, alongside the same
    fault/trigger/validation schema this project has used throughout.
    """
    os.makedirs(out_dir, exist_ok=True)

    changed_source_files = [source_file_rel, host1_file_rel, host2_file_rel]
    variant_patch = git_diff_multi(checkout_dir, changed_source_files)
    test_patch = git_diff(checkout_dir, test_file_rel)

    manifest = {
        "schema_version": "d4j-variant-manifest/v1",
        "variant_id": variant_id,
        "status": "generation_incomplete",
        "benchmark_eligible": False,
        "source": {
            "defects4j_project": project,
            "defects4j_bug_id": bug_id,
            "bug_slug": f"{project}-{bug_id}",
            "baseline_version": f"fixed revision ({project}-{bug_id}f), unmodified except for "
                                 "this hand-designed variant",
            "artifact_path": f"new_bug_variants/{project}/bug-{bug_id}/L20/{variant_id}/",
        },
        "reproducibility": {
            "status": "not_checked",
            "note": [
                f"Generated by variant_generator's chain pipeline (generate_chain.py - automated, "
                f"LLM-designed, empirically validated via real defects4j compile+test, including a "
                f"fresh-checkout reproduction gate). {seed_note} "
                f"Kind: {kind}. Bug rationale: {design.bug_rationale}"
            ],
        },
        "difficulty_axis": {
            "kind": "distance_plus_narrative_lie_plus_two_file_anonymous_chain_generated",
            "generator": "variant_generator/generate_chain.py (generalization-confirmed recipe, "
                         "HANDOFF.md Sections 11.21-11.23)",
            "predicted_correct_value": design.predicted_correct_value,
            "predicted_buggy_value": design.predicted_buggy_value,
        },
        "chain": {
            "facade_class": gold_class,
            "facade_method": facade_method,
            "hop1": {"host_class": host1_class, "method": design.hop1_method_name,
                     "anchored_after_method": anchor1_name},
            "hop2": {"host_class": host2_class, "method": design.hop2_method_name,
                     "anchored_after_method": anchor2_name},
        },
        "reasoning": {
            "level": "L20",
            # gold_method (the real fault) lives in host2_class, NOT
            # gold_class (the facade's own, original class) - unlike the
            # single-file recipe's package_variant(), where the delegate
            # stays in the same class as the facade.
            "changed_node": f"{host2_class}#{gold_method}",
        },
        "fault": {
            "locations": [{
                "class": host2_class,
                "method": design.hop2_method_name,
                "file": host2_file_rel,
                "production": True,
            }],
            "gold": {"faulty_class": host2_class, "faulty_method": design.hop2_method_name},
            "semantic_root_cause": design.bug_rationale,
        },
        "trigger": {
            "test_id": trigger_test_id,
            "all_empirically_failing_tests": failing_tests,
        },
        "artifacts": {
            "manifest": "variant_manifest.json",
            "variant_patch": "variant.patch",
            "test_patch": "test.patch",
            "validation": "validation.json",
        },
    }

    validation = {
        "schema_version": "d4j-validation/v1",
        "variant_id": variant_id,
        "status": "accepted",
        "accepted": True,
        "gate": {
            "variant_compile": {"status": "pass"},
            "variant_trigger": {"status": "expected_fail", "test_id": trigger_test_id},
            "production_fault": {"status": "pass", "known": True},
            "gold_method_known": {"status": "pass", "known": True},
            "fresh_checkout_reproduction": {"status": "pass"},
            "no_name_leak": {"status": "pass"},
        },
        "validated_with": {"baseline_revision": f"{project}-{bug_id}f"},
    }

    with open(os.path.join(out_dir, "variant_manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    with open(os.path.join(out_dir, "variant.patch"), "w") as f:
        f.write(variant_patch)
    with open(os.path.join(out_dir, "test.patch"), "w") as f:
        f.write(test_patch)
    with open(os.path.join(out_dir, "validation.json"), "w") as f:
        json.dump(validation, f, indent=2)

    return out_dir
